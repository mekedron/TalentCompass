#!/usr/bin/env python3
"""Convert a class guide JSON file into Data/<CLASS>.lua and validate its builds.

Usage: tools/json2lua.py research/WARRIOR.json [more.json ...]

Validation per build: exactly 51 points, talent names exist in the trees list,
ranks never exceed maxRank, and tier gating (5 points per tier in the same tree)
holds at every step of the order.
"""
import json
import os
import sys

TOTAL_POINTS = 51
OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Data")


def lua_str(value):
    s = str(value).replace("\u2192", "->").replace("\u2190", "<-")
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return '"' + s + '"'


def lua_list(items, indent):
    pad = "\t" * indent
    return "{\n" + "".join(f"{pad}\t{lua_str(i)},\n" for i in items) + pad + "}"


def loc_text(build, field):
    return f"{{ en = {lua_str(build.get(field + '_en', ''))}, ru = {lua_str(build.get(field + '_ru') or build.get(field + '_en', ''))} }}"


def loc_list(build, field, indent):
    en = build.get(field + "_en") or []
    ru = build.get(field + "_ru") or en
    pad = "\t" * indent
    return "{\n" + f"{pad}\ten = {lua_list(en, indent + 1)},\n{pad}\tru = {lua_list(ru, indent + 1)},\n{pad}}}"


def validate(data):
    errors = []
    talents = {}
    for tree_index, tree in enumerate(data["trees"], 1):
        for t in tree["talents"]:
            talents[t["name"]] = dict(t, tree=tree_index)
    for build in data["builds"]:
        spent_tree = {}
        ranks = {}
        total = 0
        for name, n in build["order"]:
            meta = talents.get(name)
            if not meta:
                errors.append(f"{build['id']}: unknown talent '{name}'")
                continue
            tier = meta.get("tier") or 1
            tree = meta["tree"]
            for _ in range(n):
                if spent_tree.get(tree, 0) < 5 * (tier - 1):
                    errors.append(f"{build['id']}: '{name}' (tier {tier}) taken with only {spent_tree.get(tree, 0)} points in tree {tree}")
                    break
                spent_tree[tree] = spent_tree.get(tree, 0) + 1
            ranks[name] = ranks.get(name, 0) + n
            total += n
            if meta.get("maxRank") and ranks[name] > meta["maxRank"]:
                errors.append(f"{build['id']}: '{name}' {ranks[name]} > maxRank {meta['maxRank']}")
        if total != TOTAL_POINTS:
            errors.append(f"{build['id']}: {total} points instead of {TOTAL_POINTS}")
    return errors


def convert(path):
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    cls = data["class"].upper()
    errors = validate(data)

    used = set()
    for build in data["builds"]:
        for name, _ in build["order"]:
            used.add(name)

    out = []
    out.append("-- Generated by tools/json2lua.py. Edit the source JSON and regenerate.")
    out.append(f"-- Patch: {data.get('patch', '')}")
    for src in data.get("sources", [])[:8]:
        out.append(f"-- Source: {src}")
    out.append("local _, ns = ...")
    out.append("")
    out.append(f'ns.RegisterClass("{cls}", {{')
    changes_en = data.get("forever_changes_en", "")
    changes_ru = data.get("forever_changes_ru") or changes_en
    out.append(f"\tchanges = {{ en = {lua_str(changes_en)}, ru = {lua_str(changes_ru)} }},")
    out.append("\ttalents = {")
    for tree_index, tree in enumerate(data["trees"], 1):
        out.append(f"\t\t-- {tree['name']}")
        for t in tree["talents"]:
            if t["name"] not in used:
                continue
            fields = [f"tree = {tree_index}", f"tier = {t.get('tier') or 1}", f"max = {t.get('maxRank') or 1}"]
            if t.get("spellId"):
                fields.append(f"spell = {int(t['spellId'])}")
            if t.get("name_ru"):
                fields.append(f"ru = {lua_str(t['name_ru'])}")
            out.append(f"\t\t[{lua_str(t['name'])}] = {{ {', '.join(fields)} }},")
    out.append("\t},")
    out.append("\tbuilds = {")
    for b in data["builds"]:
        out.append("\t\t{")
        out.append(f"\t\t\tid = {lua_str(b['id'])},")
        out.append(f"\t\t\trole = {lua_str(b.get('role', 'DPS'))},")
        out.append(f"\t\t\tname = {loc_text(b, 'name')},")
        out.append(f"\t\t\tsummary = {loc_text(b, 'summary')},")
        out.append("\t\t\torder = {")
        for name, n in b["order"]:
            out.append(f"\t\t\t\t{{ {lua_str(name)}, {n} }},")
        out.append("\t\t\t},")
        out.append(f"\t\t\trotation = {loc_list(b, 'rotation', 3)},")
        out.append(f"\t\t\tstats = {loc_text(b, 'stats')},")
        out.append(f"\t\t\tgear = {loc_list(b, 'gear', 3)},")
        out.append(f"\t\t\ttips = {loc_list(b, 'tips', 3)},")
        out.append("\t\t},")
    out.append("\t},")
    out.append("})")
    out.append("")

    os.makedirs(OUT_DIR, exist_ok=True)
    target = os.path.join(OUT_DIR, f"{cls}.lua")
    with open(target, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    return cls, errors


def main():
    failed = False
    for path in sys.argv[1:]:
        cls, errors = convert(path)
        status = "OK" if not errors else f"{len(errors)} problem(s)"
        print(f"{cls}: {status}")
        for e in errors:
            print("   -", e)
            failed = True
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
